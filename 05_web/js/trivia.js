  // ── Render ──
  const grid = document.getElementById('trivia-grid');

  function renderCard(t, index) {
    const flagImgs = t.flags.map((code, i) => {
      const img = `<img src="${svg(code)}" alt="${code}" loading="lazy">`;
      if (i > 0 && t.flags.length > 1) {
        return `<span class="trivia-vs">vs</span>${img}`;
      }
      return img;
    }).join('');

    const multiClass = t.flags.length > 1 ? 'multi' : '';

    const tags = t.tags.map(([label, cls]) =>
      `<span class="trivia-tag ${cls}">${label}</span>`
    ).join('');

    return `
    <article class="trivia-card" style="animation-delay:${index * 60}ms">
      <div class="trivia-episode">${t.num}</div>
      <div class="trivia-inner">
        <div class="trivia-flags ${multiClass}">
          ${flagImgs}
        </div>
        <div class="trivia-content">
          <h2 class="trivia-title">${t.title}</h2>
          <p class="trivia-body">${t.body}</p>
          <div class="trivia-tags">${tags}</div>
        </div>
      </div>
    </article>`;
  }

  grid.innerHTML = TRIVIA.map((t, i) => renderCard(t, i)).join('');

